export default {
  async fetch(request, env, ctx) {
    if (request.method !== 'POST') {
      return new Response('Method Not Allowed', { status: 405 });
    }

    try {
      const update = await request.json();
      
      if (update.message && update.message.text) {
        ctx.waitUntil(handleMessage(update.message, env));
      }
      
      return new Response('OK');
    } catch (err) {
      return new Response('Error: ' + err.message, { status: 500 });
    }
  }
};

async function handleMessage(message, env) {
  const chatId = message.chat.id;
  const text = message.text.trim();
  
  // Command: /start
  if (text === '/start') {
    await resetSession(chatId, env, true);
    return;
  }
  
  // Command: /reset
  if (text === '/reset') {
    await env.VALENTINA_KV.delete(`chat_${chatId}`);
    await sendTelegram(chatId, "Memori dihapus. Kirim /start untuk memulai dari Scene 1.", env);
    return;
  }
  
  // Load or init history
  let history = await env.VALENTINA_KV.get(`chat_${chatId}`, { type: 'json' });
  let isNew = false;
  
  if (!history) {
    history = [
      { role: 'system', content: SYSTEM_PROMPT },
      { role: 'assistant', content: SCENE_1 }
    ];
    isNew = true;
  }
  
  // Append user message
  history.push({ role: 'user', content: text });
  
  // Call model
  const reply = await callModel(history, env);
  
  // Append assistant reply and save
  history.push({ role: 'assistant', content: reply });
  await env.VALENTINA_KV.put(`chat_${chatId}`, JSON.stringify(history));
  
  // Send to Telegram
  if (isNew) {
    await sendTelegram(chatId, SCENE_1, env);
  }
  await sendTelegram(chatId, reply, env);
}

async function resetSession(chatId, env, sendScene = false) {
  const history = [
    { role: 'system', content: SYSTEM_PROMPT },
    { role: 'assistant', content: SCENE_1 }
  ];
  await env.VALENTINA_KV.put(`chat_${chatId}`, JSON.stringify(history));
  if (sendScene) {
    await sendTelegram(chatId, SCENE_1, env);
  }
}

async function callModel(messages, env) {
  const res = await fetch(env.MODEL_API_URL, {
    method: 'POST',
    headers: {
      'Authorization': `Bearer ${env.MODEL_API_KEY}`,
      'Content-Type': 'application/json'
    },
    body: JSON.stringify({
      model: env.MODEL_NAME,
      messages: messages,
      temperature: 0.85,
      max_tokens: 2048,
      stream: false
    })
  });
  
  if (!res.ok) {
    const err = await res.text();
    throw new Error(`Model API error: ${res.status} ${err}`);
  }
  
  const data = await res.json();
  return data.choices[0].message.content.trim();
}

async function sendTelegram(chatId, text, env) {
  const maxLen = 4096;
  
  if (text.length <= maxLen) {
    await fetch(`https://api.telegram.org/bot${env.TELEGRAM_BOT_TOKEN}/sendMessage`, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ chat_id: chatId, text: text })
    });
    return;
  }
  
  // Split long messages by paragraph boundaries
  const chunks = splitMessage(text, maxLen);
  for (const chunk of chunks) {
    await fetch(`https://api.telegram.org/bot${env.TELEGRAM_BOT_TOKEN}/sendMessage`, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ chat_id: chatId, text: chunk })
    });
  }
}

function splitMessage(text, max) {
  const parts = [];
  let current = '';
  const paragraphs = text.split('\n\n');
  
  for (const para of paragraphs) {
    if ((current + '\n\n' + para).length > max) {
      if (current) parts.push(current);
      current = '';
      
      if (para.length > max) {
        let remaining = para;
        while (remaining.length > max) {
          parts.push(remaining.substring(0, max));
          remaining = remaining.substring(max);
        }
        current = remaining;
      } else {
        current = para;
      }
    } else {
      current = current ? current + '\n\n' + para : para;
    }
  }
  
  if (current) parts.push(current);
  return parts;
}
